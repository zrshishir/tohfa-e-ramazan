    /**
     * Add minutes to a time string like "05:22 AM"
     */
    private function addMinutes(string $time, int $minutes): string
    {
        $ts = strtotime($time);
        return date('h:i A', $ts + $minutes * 60);
    }

    /**
     * Subtract minutes from a time string like "05:22 AM"
     */
    private function subtractMinutes(string $time, int $minutes): string
    {
        $ts = strtotime($time);
        return date('h:i A', $ts - $minutes * 60);
    }

